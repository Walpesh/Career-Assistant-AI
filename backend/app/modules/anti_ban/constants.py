"""Параметры Proxy & Anti-Ban Module — только значения из docs/04_PARSING_RULES.md.

§1  — жёсткие лимиты (задержки 4–8 с, 60–80 запросов с одного IP, ≤ 2 воркера);
§3.2 — политика ротации (sticky-сессия 5–10 минут);
§3.3 — маскировка (прогрев на https://hh.ru/, human-mimicry);
§5  — реакция на защиту (серия 404 → пауза 30–60 с, 429 → exponential backoff);
§9  — порог доли капчи (>5% → снижение интенсивности).

Все числа централизованы здесь: код модуля не содержит «магических» задержек,
любая настройка меняется в одном месте (единственная точка конфигурации).
"""

from __future__ import annotations

# ---------------------------------------------------------------- docs/04 §1 ---
# «Случайная задержка 4–8 секунд между запросами (лучше нормальное распределение)».
DELAY_MIN_SECONDS = 4.0
DELAY_MAX_SECONDS = 8.0
# Нормальное распределение: μ — середина интервала, σ = 1.0 (±2σ = интервал 4–8),
# значения за границами обрезаются (clipping), чтобы лимит не нарушался.
DELAY_MEAN_SECONDS = (DELAY_MIN_SECONDS + DELAY_MAX_SECONDS) / 2.0  # 6.0
DELAY_SIGMA_SECONDS = 1.0

# «Не более 60–80 запросов с одного IP» → принудительная ротация прокси.
REQUESTS_PER_IP_MIN = 60
REQUESTS_PER_IP_MAX = 80

# «Максимум 2 одновременных парсинг-воркера» на пользователя.
MAX_CONCURRENT_PARSERS_PER_USER = 2

# Рекомендуемый суточный объём: 300–500 вакансий (для мониторинга интенсивности).
DAILY_VACANCIES_MIN = 300
DAILY_VACANCIES_MAX = 500

# --------------------------------------------------------------- docs/04 §3.2 ---
# «Sticky-сессия: 5–10 минут на один IP» → ротация по истечении времени.
STICKY_SESSION_MIN_SECONDS = 5 * 60  # 300
STICKY_SESSION_MAX_SECONDS = 10 * 60  # 600

# --------------------------------------------------------------- docs/04 §3.3 ---
# «Прогрев сессии: первый запрос всегда на https://hh.ru/».
WARMUP_URL = "https://hh.ru/"

# Human-mimicry для Playwright (docs/04 §3.3): «небольшие паузы «чтения» страницы»,
# «случайный скролл», «движения мыши по кривым Безье». Численно в docs/04 не
# заданы — параметры модуля (тоже централизованы, не разбросаны по коду).
READING_PAUSE_MIN_SECONDS = 0.4
READING_PAUSE_MAX_SECONDS = 1.6
MOUSE_MOVE_STEPS = 24  # точек в траектории движения мыши
SCROLL_STEPS_MIN = 3  # кол-во рывков скролла за «сессию чтения»
SCROLL_STEPS_MAX = 6
SCROLL_STEP_PX_MIN = 80  # размер одного рывка скролла, px
SCROLL_STEP_PX_MAX = 320

# --------------------------------------------------------------- docs/04 §5 -----
# «HTTP 429 → смена прокси + exponential backoff». База backoff'а = максимуму
# задержки между запросами из §1 (8 с); потолок — чтобы не зависать надолго.
BACKOFF_BASE_SECONDS = DELAY_MAX_SECONDS  # 8
BACKOFF_CAP_SECONDS = 300.0  # 5 минут
# Попыток на один запрос (включая первую): 429/5xx/троттлинг ретраятся, капча — нет.
MAX_FETCH_ATTEMPTS = 4

# «Серия 404 на карточках → пауза 30–60 сек + смена IP».
THROTTLING_PAUSE_MIN_SECONDS = 30.0
THROTTLING_PAUSE_MAX_SECONDS = 60.0
# Размер «серии» подряд идущих 404. В docs/04 §5 размер серии не указан —
# параметр модуля (3 карточки подряд = подозрение на троттлинг, а не удаление).
CONSECUTIVE_404_THRESHOLD = 3

# Ответ hh.ru может быть длинным; для детекта капчи/429 достаточно начала.
DETECTION_BODY_LIMIT = 20_000  # символов тела ответа, участвующих в детекте

# --------------------------------------------------------------- docs/04 §9 -----
# «При росте доли капчи > 5% — автоматически снижать интенсивность парсинга».
CAPTCHA_RATE_THRESHOLD = 0.05
