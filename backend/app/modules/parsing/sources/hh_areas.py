#: Все виды тире и минус, которые пользователь может ввести вместо дефиса.
_DASHES = "\u2010\u2011\u2012\u2013\u2014\u2015\u2212-"


def normalize_city_name(value: object) -> str:
    """Привести название города к форме ключа карты.

    Обрезка пробелов, нижний регистр, «ё» → «е», унификация дефисов (минус,
    короткое и длинное тире) и сжатие повторов пробелов: ``" Санкт - Петербург "``
    и ``"Санкт-Петербург"`` дают один и тот же ключ.
    """
    text = str(value or "").strip().lower().replace("\u0451", "\u0435")
    text = re.sub(f"[{_DASHES}]", "-", text)
    text = re.sub(r"\s*-\s*", "-", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def resolve_city_area(value: object) -> int | None:
    """id территории hh.ru по названию города либо ``None``.

    ``None`` — для пустого и неизвестного города: предупреждение в лог пишет
    вызывающий код (см. ``HHAdapter._resolve_city_area``).
    """
    key = normalize_city_name(value)
    if not key:
        return None
    return _CITY_AREA_MAP.get(key)
